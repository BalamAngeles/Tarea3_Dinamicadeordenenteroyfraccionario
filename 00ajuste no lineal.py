def ajustar(datos, nombre, color=None):
    """Ajusta el modelo v0*exp(-b*t) a los datos {t, v} y devuelve resultados."""
    d = np.array(datos, dtype=float)
    t_data = d[:, 0]
    v_data = d[:, 1]

    # Valor inicial para v0 y b
    p0 = [v_data[0], 1.0]

    popt, pcov = curve_fit(modelo, t_data, v_data, p0=p0, maxfev=10000)
    v0 = popt[0]
    b = popt[1]
    v0_err = np.sqrt(np.diag(pcov))[0]
    b_err = np.sqrt(np.diag(pcov))[1]

    # Prediccion del modelo ajustado
    v_pred = modelo(t_data, v0, b)

    # Coeficiente de determinacion R^2
    ss_res = np.sum((v_data - v_pred) ** 2)
    ss_tot = np.sum((v_data - np.mean(v_data)) ** 2)
    r2 = 1 - ss_res / ss_tot

    print("=" * 50)
    print(f"AJUSTE NO LINEAL - {nombre}")
    print("=" * 50)
    print(f"v0 ajustado = {v0:.6f}")
    print(f"v0 error estandar = {v0_err:.4e}")
    print(f"b ajustado = {b:.6f}")
    print(f"b error estandar = {b_err:.4e}")
    print(f"R^2 = {r2:.6f}")
    print()

    return t_data, v_data, v0, b, r2


